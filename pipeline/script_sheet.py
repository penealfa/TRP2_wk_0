"""Write RECORDING_SCRIPT.md: every narration line with the file name to save the
take under, the English meaning, the target length and delivery notes. Print it
or open it on a second screen while recording.

    python -m pipeline.script_sheet
"""
from __future__ import annotations

from pipeline.common import ROOT, load_storyboard, main_guard

WPS = 2.3


def main() -> int:
    sb = load_storyboard()
    lines = [f"# Recording script: {sb['title']}", "",
             f"Language: {sb['language']['name']}. Narrator: {sb['defaults'].get('narrator', '')}", "",
             "How to record: a quiet room with soft furnishings, phone 20-30 cm from your mouth, "
             "airplane mode on. Leave one second of silence before and after each line. Record each "
             "line as its own file and save it in `recordings/` under the name shown. Do two or three "
             "takes of the lines that matter most and keep the best one. Re-recording a line later "
             "only rebuilds that shot.", ""]
    voices = sb["defaults"].get("voices", {})
    for s in sb["shots"]:
        n = s["narration"]
        if not n["text"].strip():
            continue
        spk = n.get("speaker")
        if spk and voices.get(spk, {}).get("source") == "tts":
            lines += [f"## {s['id']}  ({spk}, generated by TTS: not recorded)", "", f"> {n['text']}", ""]
            continue
        secs = len(n["text"].split()) / WPS
        lines += [f"## {s['id']}  →  `recordings/{s['id']}.wav` (or .m4a)",
                  "", f"> {n['text']}", "",
                  f"- Meaning: {n['text_en']}" if n["text"] != n["text_en"] else "",
                  f"- Shot on screen: {s['keyframe']['prompt']}",
                  f"- Feeling: {n.get('style') or s['reason']}",
                  f"- Aim for about {secs:.0f}s (shot holds {s['duration_s']}s)", ""]
    (ROOT / "RECORDING_SCRIPT.md").write_text("\n".join(l for l in lines if l is not None) + "\n", encoding="utf-8")
    print("wrote RECORDING_SCRIPT.md")
    return 0


if __name__ == "__main__":
    main_guard(main)
